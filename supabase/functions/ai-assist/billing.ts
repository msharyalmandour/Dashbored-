// معرفة الاشتراك والدفع للمساعد الذكي — بدون أي imports عشان تنختبر محليًا
// بأي بيئة (node/deno). كل معلومة هنا مأخوذة من الكود الفعلي للموقع
// (moyasar-webhook، MoyasarPayment، CheckoutModal، subscription.ts) مو من
// افتراضات — وأي شي مو محدد بعد بالمنتج (سياسة الاسترداد، قناة الدعم)
// نقوله للمساعد صراحة "غير محدد" عشان ما يختلقه.

// الكلمات العربية تُطابق كجزء من الكلمة (العربي ما له حدود كلمات بـ JS)، أما
// الإنجليزية فبحدود كلمة كاملة \b — وإلا "cardiac" و"discharge" (مصطلحات
// تمريض شائعة جدًا) كانت تنطبق على "card" و"charge" بالغلط
const BILLING_INTENT = new RegExp(
  "(دفع|ادفع|دفعت|دفعنا|ميسر|مويسر|اشتراك|اشترك|انسحب|سحبو|خصمو|خصم مبلغ|فاتور|بطاق|استرداد|استرجاع|ارجاع|إرجاع|تجديد|جدد|سعر|اسعار|أسعار|مبلغ|ريال|تكلفة|تحويل)" +
    "|\\b(moyasar|stc|refund|refunds|charged|charges|payment|payments|billing|subscription|invoice|credit card|price|pricing)\\b",
  "i",
);

/** هل آخر رسالة من المستخدمة تخص الدفع/الاشتراك؟ — نجيب معلومات الفريق
    الفعلية من قاعدة البيانات فقط بهذي الحالة، عشان ما نزيد تكلفة ولا
    استعلامات على كل سؤال بحثي عادي */
export function isBillingQuestion(text: string): boolean {
  return BILLING_INTENT.test(text);
}

/** يطلع نص السؤال من آخر رسالة مستخدمة (نص عادي أو مصفوفة أجزاء فيها صورة) */
export function lastUserText(
  messages: Array<{ role: string; content: unknown }>,
): string {
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i];
    if (m.role !== "user") continue;
    if (typeof m.content === "string") return m.content;
    if (Array.isArray(m.content)) {
      return m.content
        .filter((b): b is { type: string; text: string } => !!b && (b as { type?: string }).type === "text")
        .map((b) => b.text)
        .join(" ");
    }
    return "";
  }
  return "";
}

export interface BillingFactsInput {
  gateway: "live" | "test" | "unknown";
  subscriptionEndDate: string | null;
  onTrial: boolean;
  monthlyPrice: number;
  memberCount: number;
  todayISO: string;
  payments: Array<{ amount: number; createdAtISO: string; byMe: boolean }>;
  supportContact?: string | null;
}

function daysBetween(fromISO: string, toISO: string): number {
  const a = Date.UTC(+fromISO.slice(0, 4), +fromISO.slice(5, 7) - 1, +fromISO.slice(8, 10));
  const b = Date.UTC(+toISO.slice(0, 4), +toISO.slice(5, 7) - 1, +toISO.slice(8, 10));
  return Math.round((b - a) / 86_400_000);
}

/** كم يوم تمدد دفعة بهذا المبلغ — نفس معادلة moyasar-webhook بالضبط */
export function daysForPayment(amount: number, monthlyPrice: number, memberCount: number): number {
  const total = monthlyPrice * Math.max(memberCount, 1);
  return total > 0 ? Math.max(Math.round((amount / total) * 30), 1) : 30;
}

/** كتلة "معلومات فعلية عن فريقك" — أرقام وتواريخ فقط، بدون أسماء أو نصوص
    يكتبها المستخدمون (عشان ما يصير حقن تعليمات داخل موجّه النظام) */
export function buildBillingFacts(f: BillingFactsInput): string {
  const lines: string[] = ["معلومات فعلية عن اشتراك فريق هذي المستخدمة (من قاعدة البيانات الآن — اعتمديها ولا تخمّني غيرها):"];

  if (!f.subscriptionEndDate) {
    lines.push("- حالة الاشتراك: لم يُفعّل بعد (الفريق بوضع قراءة فقط).");
  } else {
    const left = daysBetween(f.todayISO, f.subscriptionEndDate);
    if (left < 0) {
      lines.push(`- حالة الاشتراك: منتهي منذ ${-left} يوم (انتهى بتاريخ ${f.subscriptionEndDate}) — الفريق بوضع قراءة فقط.`);
    } else {
      lines.push(
        `- حالة الاشتراك: ${f.onTrial ? "فترة تجربة مجانية" : "نشط"} — ينتهي ${f.subscriptionEndDate} (باقي ${left} يوم).`,
      );
    }
  }
  lines.push(`- السعر المسجّل لفريقها: ${f.monthlyPrice} ريال شهريًا لكل عضو، وعدد الأعضاء الحالي ${f.memberCount} (إجمالي الفاتورة الكاملة ${f.monthlyPrice * f.memberCount} ريال).`);

  if (f.payments.length === 0) {
    lines.push("- الدفعات المسجّلة بالنظام لفريقها: لا توجد أي دفعة مسجّلة.");
  } else {
    lines.push(`- آخر الدفعات المسجّلة بالنظام لفريقها (الأحدث أولًا، ${f.payments.length}):`);
    for (const p of f.payments) {
      const days = daysForPayment(p.amount, f.monthlyPrice, f.memberCount);
      lines.push(`  • ${p.createdAtISO.slice(0, 10)} — ${p.amount} ريال — ${p.byMe ? "دفعتها هي بنفسها" : "دفعها عضو آخر"} — مدّدت الاشتراك حوالي ${days} يوم`);
    }
  }

  if (f.gateway === "test") {
    lines.push(
      "- بوابة الدفع بالبطاقة (Moyasar) حاليًا بالوضع التجريبي (Test): هذا الوضع ما يسحب مبالغ حقيقية من بطاقات فعلية. يعني لو قالت إن مبلغ حقيقي انسحب من بطاقتها، فما جاء من نموذج الدفع بالموقع بوضعه الحالي.",
    );
  } else if (f.gateway === "live") {
    lines.push("- بوابة الدفع بالبطاقة (Moyasar) بالوضع الحقيقي (Live): الدفعات اللي تنجح بالبطاقة حقيقية وتسحب مبلغ فعلي.");
  } else {
    lines.push("- وضع بوابة الدفع (تجريبي أو حقيقي) غير معروف لك الآن — لا تقولي عنه شي.");
  }

  lines.push(
    f.supportContact
      ? `- قناة التواصل مع فريق Wesync للحالات اللي تحتاج مراجعة بشرية: ${f.supportContact}`
      : "- قناة تواصل محددة مع فريق Wesync: غير محددة لك — قولي لها تتواصل مع فريق Wesync مباشرة (الجهة اللي أرسلت لها رابط الموقع)، ولا تختلقي رقم أو إيميل.",
  );
  return lines.join("\n");
}

