export interface Tip {
  level: "warn" | "info";
  title: string;
  why: string;
  bad?: string;
  good?: string;
}

const LEADING = ["ألا تعتقد", "ألا ترى", "أليس", "بلا شك", "من الواضح", "من المؤكد", "لا شك", "رائع", "ممتاز", "سيئ جدًا", "فظيع"];
const ABSOLUTES = ["دائمًا", "دائما", "أبدًا", "أبدا", "كل ", "جميع", "مطلقًا", "مطلقا"];
const QUALITY_WORDS = ["راضٍ", "راضي", "راضية", "جيد", "جيدة", "سهل", "سهلة", "مفيد", "مفيدة", "واضح", "واضحة", "سريع", "سريعة", "مناسب", "مناسبة", "جودة", "سعر", "تكلفة"];

/** يفحص سؤالًا واحدًا ويرجّع نصائح قصيرة تعلّم بدل ما ترفض */
export function lintQuestion(q: Question): Tip[] {
  const tips: Tip[] = [];
  const t = q.text.trim();
  if (!t) return [{ level: "info", title: "اكتبوا نص السؤال", why: "السؤال الجيد قصير وواضح ويقيس شي واحد فقط." }];

  if (LEADING.some((w) => t.includes(w))) {
    tips.push({
      level: "warn",
      title: "سؤال موجِّه",
      why: "الصياغة توحي بالإجابة «الصحيحة» فتدفع المشارك لها. هذا يسمى تحيّزًا (Bias) ويخرّب نتائجكم.",
      bad: "ألا تعتقد أن الخدمة ممتازة؟",
      good: "ما مدى رضاك عن الخدمة؟ (مقياس من ١ إلى ٥)",
    });
  }
  const qualityHits = QUALITY_WORDS.filter((w) => t.includes(w)).length;
  if (/\sو\s?\S/.test(t) && (qualityHits >= 2 || /\sو(ال)?\S+\s+و/.test(t))) {
    tips.push({
      level: "warn",
      title: "ممكن يكون سؤال مزدوج",
      why: "لو سألتم عن شيئين بسؤال واحد، المشارك ما يعرف يجاوب إذا رأيه بالأول غير الثاني، وأنتم ما تعرفون أي واحد قصد.",
      bad: "هل أنت راضٍ عن جودة الخدمة وسعرها؟",
      good: "سؤال للجودة، وسؤال ثاني للسعر",
    });
  }
  if (ABSOLUTES.some((w) => t.includes(w)) && q.type === "likert") {
    tips.push({
      level: "info",
      title: "كلمات مطلقة (دائمًا / أبدًا / كل)",
      why: "الناس نادرًا تقول «دائمًا» أو «أبدًا» بصدق، فتتجمع الإجابات بطرف واحد. الأفضل «غالبًا» أو «أحيانًا».",
      bad: "أنا دائمًا ألتزم بالمواعيد.",
      good: "ألتزم بالمواعيد في معظم الأحيان.",
    });
  }
  if (t.length > 140) {
    tips.push({
      level: "info",
      title: "السؤال طويل",
      why: "الأسئلة الطويلة تنقرأ بسرعة وتنفهم غلط، خصوصًا على الجوال. حاولوا تختصرون تحت سطرين.",
    });
  }
  if ((q.type === "single" || q.type === "multi") && q.options) {
    const opts = q.options.map((o) => o.trim()).filter(Boolean);
    if (opts.length < 2) {
      tips.push({ level: "warn", title: "أضيفوا خيارين على الأقل", why: "سؤال الاختيار يحتاج خيارات واضحة ومتقابلة." });
    }
    if (new Set(opts).size !== opts.length) {
      tips.push({ level: "warn", title: "فيه خيارات مكررة", why: "الخيارات المكررة تربك المشارك وتخرّب العدّ." });
    }
    if (opts.length >= 3 && !opts.some((o) => /أخرى|غير ذلك|لا أعرف|لا أرغب/.test(o)) && !/عمر|جنس|مرحلة|كم/.test(t)) {
      tips.push({
        level: "info",
        title: "فكّروا تضيفون «أخرى» أو «لا أعرف»",
        why: "لو ما فيه خيار ينطبق على المشارك يضطر يختار غلط أو يترك السؤال. خيار «أخرى» يحفظ لكم دقة البيانات.",
      });
    }
  }
  if (q.type === "text") {
    tips.push({
      level: "info",
      title: "الأسئلة المفتوحة صعبة التحليل",
      why: "كل رد لازم تقرؤونه وتصنّفونه يدويًا. استخدموا سؤال مفتوح واحد أو اثنين بالأكثر، وفي النهاية (مثل «أي اقتراح؟»).",
    });
  }
  if (q.type === "likert" && !/[.!]$/.test(t) && /\?|؟/.test(t)) {
    tips.push({
      level: "info",
      title: "ليكرت يحتاج «عبارة» مو سؤال",
      why: "خيارات (أوافق ... لا أوافق) تركّب مع عبارة خبرية، مو مع سؤال «هل…؟».",
      bad: "هل الموقع سهل الاستخدام؟",
      good: "الموقع سهل الاستخدام.",
    });
  }
  return tips;
}

export interface SurveyLike {
  title: string;
  goal: string;
  questions: Question[];
  consent_text: string;
}

/** ملاحظات على الاستبيان ككل (طول، ترتيب، موافقة) */
export function lintSurvey(s: SurveyLike): Tip[] {
  const tips: Tip[] = [];
  const n = s.questions.length;
  if (!s.goal.trim()) tips.push({ level: "warn", title: "اكتبوا هدف الاستبيان أول", why: "كل سؤال لازم يخدم سؤال بحثكم. بدون هدف واضح ينتهي الاستبيان بأسئلة ما تحتاجونها." });
  if (n === 0) tips.push({ level: "info", title: "لسا ما أضفتم أسئلة", why: "ابدؤوا بأهم سؤال يجاوب هدفكم، وبعدها البيانات العامة." });
  if (n > 25) tips.push({ level: "warn", title: `${n} سؤال — طويل`, why: "بعد ١٠ دقايق ينسحب كثير من المشاركين أو يجاوبون بدون تركيز. قصّوا لكل سؤال ما يخدم هدفكم مباشرة." });
  const minutes = Math.max(1, Math.round((n * 20) / 60));
  if (n > 0) tips.push({ level: "info", title: `الوقت المتوقع: حوالي ${minutes} دقيقة`, why: "ذكروا الوقت بأول الاستبيان — يرفع نسبة الإكمال." });
  const hasDemo = s.questions.some((q) => /عمر|جنس|مرحلة|تخصص/.test(q.text));
  if (n > 0 && !hasDemo) tips.push({ level: "info", title: "ما فيه بيانات عامة", why: "غالبًا تحتاجون وصف العينة (العمر، الجنس، المرحلة) بجدول أول النتائج." });
  const likert = s.questions.filter((q) => q.type === "likert").length;
  if (likert > 0 && likert < 3) tips.push({ level: "info", title: "لحساب الثبات (ألفا كرونباخ) تحتاجون ٣ عبارات ليكرت أو أكثر تقيس نفس الفكرة", why: "الثبات = هل العبارات متّسقة مع بعضها." });
  if (!s.consent_text.trim()) tips.push({ level: "warn", title: "الموافقة المستنيرة مطلوبة", why: "قبل ما يبدأ المشارك لازم يعرف الهدف ويعرف أن مشاركته اختيارية ومجهولة." });
  return tips;
}

